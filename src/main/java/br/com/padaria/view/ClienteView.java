public boolean InserirCliente() {

    String nome = nomeCliente.getText().trim();

    String cpf = Cpf_cliente.getText().replaceAll("[^0-9]", "");

    String cep = cepCliente.getText().replaceAll("[^0-9]", "");

    String telefone = telefoneCliente.getText().replaceAll("[^0-9]", "");

    String idadeTexto = idadeCliente.getText().trim();

    if (nome.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Informe o nome."
        );
        return false;
    }

    if (cpf.length() != 11) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Informe um CPF valido."
        );
        return false;
    }

    if (telefone.length() != 11) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Informe um telefone valido."
        );
        return false;
    }

    if (cep.length() != 8) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Informe um CEP valido."
        );
        return false;
    }

    if (idadeTexto.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Informe a idade."
        );
        return false;
    }

    try {
        Integer.parseInt(idadeTexto);
    } catch (NumberFormatException erro) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "A idade deve conter apenas numeros."
        );
        return false;
    }

    try {
            Cliente cliente = clienteEmEdicao == null ? new Cliente() : clienteEmEdicao;
            Sexualidade sexualidade = getSexualidadeSelecionada();
            if (sexualidade == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma sexualidade.");
                return false;
            }

            cliente.setIdSexualidade(sexualidade.getIdGenero());
            cliente.setNome(nome);
            cliente.setSobrenome(sobrenomeCliente.getText().trim());
            cliente.setCpf(cpf);
            cliente.setTelefone(telefoneCliente.getText().trim());
            cliente.setCep(cep);
            cliente.setRua(ruaCliente.getText().trim());
            cliente.setBairro(bairroCliente.getText().trim());
            cliente.setCidade(dsCidade.getText().trim());
            cliente.setUf(ufCliente.getText().trim().toUpperCase());
            cliente.setComplemento(complementoCliente.getText().trim());
            cliente.setLogradouro(logadrouroCliente.getText().trim());

            String numero = numeroCasaCliente.getText().trim();
            if (!numero.isEmpty()) {
                cliente.setNumero(Integer.parseInt(numero));
            }

            String dataNascimento = dataNascimentCliente.getText().trim();
            if (!dataNascimento.isEmpty()){
                
                DateTimeFormatter formato = 
                        DateTimeFormatter.ofPattern ("dd/MM/yyyy");
                
                LocalDate nascimento = 
                        LocalDate.parse(dataNascimento, formato);
                
                int idadeCalculada =
                        Period.between(nascimento, LocalDate.now()).getYears();
                
                if(idadeCalculada != Integer.parseInt(idadeTexto)) {
                    javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "A idade informada nao corresponde à data de nascimento."
                    );
                    return false;
                }
                cliente.setDataNascimento(nascimento);
            }
           
            ClienteDao dao = new ClienteDao();
            if (clienteEmEdicao == null) {
                dao.inserir(cliente);
            } else {
                dao.atualizar(cliente);
            }

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    clienteEmEdicao == null
                            ? "Cliente cadastrado com sucesso!"
                            : "Cliente atualizado com sucesso!"
            );
            if (clienteEmEdicao == null) {
                limparCampos();
            } else {
                dispose();
            }
            return true;
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "O numero da casa deve conter apenas numeros."
            );
        } catch (DateTimeParseException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Informe a data de nascimento no formato dd/MM/aaaa."
            );
        } catch (RuntimeException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    clienteEmEdicao == null
                            ? "Nao foi possivel cadastrar o cliente."
                            : "Nao foi possivel atualizar o cliente."
            );
        }
        return false;
    }

    private void limparCampos() {
        nomeCliente.setText("");
        sobrenomeCliente.setText("");
        idadeCliente.setText("");
        Cpf_cliente.setText("");
        telefoneCliente.setText("");
        generoCliente.setSelectedIndex(0);
        dsCidade.setText("");
       
        cepCliente.setText("");
        ruaCliente.setText("");
        numeroCasaCliente.setText("");
        bairroCliente.setText("");
        ufCliente.setText("");
        complementoCliente.setText("");
        dataNascimentCliente.setText("");
        logadrouroCliente.setText("");
        ultimoCepConsultado = "";
    }

    public void carregarSexualidades(String selecionar) {
        try {
            carregandoSexualidades = true;
            SexualidadeDao dao = new SexualidadeDao();
            sexualidades = dao.listarAtivas();
            generoCliente.removeAllItems();

            for (Sexualidade sexualidade : sexualidades) {
                generoCliente.addItem(sexualidade.getDescricao());
            }

            generoCliente.addItem("Outros");

            if (selecionar != null) {
                generoCliente.setSelectedItem(selecionar);
            }
        } catch (RuntimeException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Nao foi possivel carregar as sexualidades."
            );
        } finally {
            carregandoSexualidades = false;
        }
    }

    private Sexualidade getSexualidadeSelecionada() {
        int posicao = generoCliente.getSelectedIndex();

        if (posicao >= 0 && posicao < sexualidades.size()) {
            return sexualidades.get(posicao);
        }
        return null;
    }

    private void configurarConsultaCep() {
        cepCliente.addActionListener(evt -> consultarCep());
        cepCliente.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusLost(java.awt.event.FocusEvent evt) {
                consultarCep();
            }
        });
    }

    private void consultarCep() {
        String cep = cepCliente.getText().replaceAll("[^0-9]", "");

        if (cep.isEmpty()) {
            return;
        }

        if (cep.length() != 8) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe um CEP com 8 numeros.");
            return;
        }

        if (consultandoCep || cep.equals(ultimoCepConsultado)) {
            return;
        }

        consultandoCep = true;
        cepCliente.setEnabled(false);

        javax.swing.SwingWorker<Cliente, Void> consulta = new javax.swing.SwingWorker<Cliente, Void>() {
            @Override
            protected Cliente doInBackground() throws Exception {
                return clienteController.buscarEnderecoPorCep(cep);
            }

            @Override
            protected void done() {
                try {
                    Cliente clienteEndereco = get();

                    if (clienteEndereco == null) {
                        ultimoCepConsultado = cep;
                        javax.swing.JOptionPane.showMessageDialog(
                                ClienteView.this,
                                "CEP nao encontrado."
                        );
                        return;
                    }

                    ultimoCepConsultado = cep;
                    if (clienteEndereco.getCep() != null) {
                        cepCliente.setText(clienteEndereco.getCep());
                    }
                    logadrouroCliente.setText(clienteEndereco.getRua());
                    ruaCliente.setText(clienteEndereco.getRua());
                    bairroCliente.setText(clienteEndereco.getBairro());
                    dsCidade.setText(clienteEndereco.getCidade());
                    ufCliente.setText(clienteEndereco.getUf());
                    numeroCasaCliente.requestFocus();
                } catch (InterruptedException ex) {
                    Thread.currentThread().interrupt();
                    ultimoCepConsultado = "";
                    mostrarErroCep();
                } catch (ExecutionException ex) {
                    ultimoCepConsultado = "";
                    mostrarErroCep();
                } finally {
                    consultandoCep = false;
                    cepCliente.setEnabled(true);
                }
            }
        };

        consulta.execute();
    }

    private void mostrarErroCep() {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Nao foi possivel consultar o CEP. Verifique sua conexao."
        );
    }

    private void carregarClienteNaTela() {
        nomeCliente.setText(clienteEmEdicao.getNome());
        sobrenomeCliente.setText(clienteEmEdicao.getSobrenome());
        Cpf_cliente.setText(clienteEmEdicao.getCpf());
        telefoneCliente.setText(clienteEmEdicao.getTelefone());
        cepCliente.setText(clienteEmEdicao.getCep());
        ruaCliente.setText(clienteEmEdicao.getRua());
        bairroCliente.setText(clienteEmEdicao.getBairro());
        dsCidade.setText(clienteEmEdicao.getCidade());
        ufCliente.setText(clienteEmEdicao.getUf());
        complementoCliente.setText(clienteEmEdicao.getComplemento());
        logadrouroCliente.setText(clienteEmEdicao.getLogradouro());

        if (clienteEmEdicao.getNumero() != null) {
            numeroCasaCliente.setText(clienteEmEdicao.getNumero().toString());
        }

        if (clienteEmEdicao.getDataNascimento() != null) {
            DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            dataNascimentCliente.setText(clienteEmEdicao.getDataNascimento().format(formato));
            int idade = Period.between(clienteEmEdicao.getDataNascimento(), LocalDate.now()).getYears();
            idadeCliente.setText(String.valueOf(idade));
        }

        carregandoSexualidades = true;
        generoCliente.setSelectedIndex(-1);
        try {
            for (int i = 0; i < sexualidades.size(); i++) {
                if (sexualidades.get(i).getIdGenero() == clienteEmEdicao.getIdSexualidade()) {
                    generoCliente.setSelectedIndex(i);
                    break;
                }
            }
        } finally {
            carregandoSexualidades = false;
        }

        ultimoCepConsultado = clienteEmEdicao.getCep() == null
                ? ""
                : clienteEmEdicao.getCep().replaceAll("[^0-9]", "");
    }


