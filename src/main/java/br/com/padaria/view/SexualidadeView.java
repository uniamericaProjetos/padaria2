    private void cadastrarSexualidade() {
        String descricao = txtDescricao.getText().trim();
        String sigla = txtSigla.getText().trim();

        if (descricao.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe o nome.");
            return;
        }

        if (descricao.equalsIgnoreCase("Outros")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe uma sexualidade diferente.");
            return;
        }
        
        //sigla vazia, usa primeira letra do nome
        if(sigla.isEmpty()){
            sigla = descricao.substring(0,1).toUpperCase();
        }

        try {
            Sexualidade sexualidade = new Sexualidade();
            sexualidade.setDescricao(descricao);
            sexualidade.setSigla(sigla);
            
            dao.inserir(sexualidade);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Sexualidade cadastrada com sucesso!"
            );

            if (clienteView != null) {
                //aberta pela tela de cliente, atualiza o combo e fecha
                clienteView.carregarSexualidades(descricao);
                dispose();
            }else{
                //aberta sozinha mostra novo registro na tabela
                carregarTabela();
                txtDescricao.setText("");
                txtSigla.setText("");
                txtDescricao.requestFocus();
            }
        } catch (RuntimeException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Nao foi possivel cadastrar a sexualidade."
            );
        }
    }
    //preenche com todas as sexualidades
    private void carregarTabela() {
        //pega o modelo da tabela e apaga as linhas que ja estavam la
        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) TbSexualidade.getModel();
        modelo.setRowCount(0);
        
        try {
            //para cada sexualidade vinda do banco, adiciona uma linha
            for (Sexualidade s : dao.listarTodas()) {
                //a ordem tem que ser a das colunas: ID, Sigla, Descricao, Status
                modelo.addRow(new Object[] {
                    s.getIdGenero(),
                    s.getSigla(),
                    s.getDescricao(),
                    s.getStatus()
                });
            }
        } catch(RuntimeException ex){
            //o DAO lanca RuntimeException quando o banco da erro
            javax.swing.JOptionPane.showMessageDialog(this, "Nao foi possivel carregar a tabela.");
        }
        }
    
    private void inativarSexualidade(){
        //linha selecionada na tabela, -1 significa que nenhuma foi
        int linha = TbSexualidade.getSelectedRow();
        
        if (linha ==-1){
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma sexualidade na tabela.");
            return; //para aqui, nao inativa nada
        }
        
        //pega o id (col 0) e status (col 3) da linha
        int id = (int) TbSexualidade.getValueAt(linha,0);
        String status = (String) TbSexualidade.getValueAt(linha, 3);
        
        if("inativo".equals(status)){
            javax.swing.JOptionPane.showMessageDialog(this, "Esta sexualidade ja esta inativa");
            return;
        }
        
        //pergunta antes de inativar
        int opcao = javax.swing.JOptionPane.showConfirmDialog(this,
                "Deseja inativar esta sexualidade?", "Confirmar",
                javax.swing.JOptionPane.YES_NO_OPTION);
        if(opcao == javax.swing.JOptionPane.YES_OPTION){
                try{
                    dao.inativar(id);
                    carregarTabela();
                } catch (RuntimeException ex){
                    javax.swing.JOptionPane.showMessageDialog(this, "Nao foi possivel inativar a sexualidade.");
                }
        }
    }
