    private void cadastrarProduto() {
        String nome = jTextField1.getText().trim();
        String quantidadeTexto = jTextField6.getText().trim();
        String precoTexto = jTextField4.getText().trim().replace(",", ".");
        String dataFabricacaoTexto = jFormattedTextField1.getText().trim();
        String dataValidadeTexto = txtDataValidade.getText().trim();

    if (nome.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Informe o nome.");
    return;
    }

    if (quantidadeTexto.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Informe a quantidade.");
    return;
    }

    if (precoTexto.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Informe o preco.");
    return;
    }

    if (dataFabricacaoTexto.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Informe a data de fabricacao.");
    return;
    }

    if (dataValidadeTexto.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Informe a data de validade.");
    return;
    }

        try {
            int quantidade = Integer.parseInt(quantidadeTexto);
            double preco = Double.parseDouble(precoTexto);

        if (quantidade <= 0 || preco <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Quantidade e preco devem ser maiores que zero."
        );
        return;
        }
            DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            LocalDate dataFabricacao = LocalDate.parse(dataFabricacaoTexto, formato);
            LocalDate dataValidade = LocalDate.parse(dataValidadeTexto, formato);

            if (dataValidade.isBefore(dataFabricacao)) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "A validade nao pode ser anterior a fabricacao."
                );
                return;
            }

            Produto produto = new Produto();
            produto.setNome(nome);
            produto.setDescricao(jTextField2.getText().trim());
            produto.setQuantidade(quantidade);
            produto.setPreco(preco);
            produto.setDataFabricacao(dataFabricacao);
            produto.setDataValidade(dataValidade);
            produto.setStatus(cmbStatus.getSelectedItem().toString());

           
           ProdutoDao dao = new ProdutoDao();
            
            
            if (idProdutoEdicao == null) {
                dao.salvarProduto(produto);
                javax.swing.JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso!");
                limparCampos();
            } 
            
            else {
                produto.setId(idProdutoEdicao); 
                dao.atualizarProduto(produto);
                javax.swing.JOptionPane.showMessageDialog(this, "Produto atualizado com sucesso!");
                this.dispose(); 
            }



            
            limparCampos();
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Informe uma quantidade e um preco validos."
            );
        } catch (DateTimeParseException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Informe as datas no formato dd/MM/aaaa."
            );
        } catch (RuntimeException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Nao foi possivel cadastrar o produto."
            );
        }
    }

    private void limparCampos() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField4.setText("");
        jTextField6.setText("");
        txtDataValidade.setText("");
        jFormattedTextField1.setText("");
        cmbStatus.setSelectedIndex(0);
    }
    
    public void preencherParaEdicao(Produto p) {
        // Preenche as caixas de texto com os dados do produto selecionado
        this.idProdutoEdicao = p.getId();
        jTextField1.setText(p.getNome());
        jTextField2.setText(p.getDescricao());
        jTextField6.setText(String.valueOf(p.getQuantidade()));
        jTextField4.setText(String.valueOf(p.getPreco()));
        
        // Formata e preenche as datas
        java.time.format.DateTimeFormatter formato = java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy");
        if (p.getDataFabricacao() != null) {
            jFormattedTextField1.setText(p.getDataFabricacao().format(formato));
        }
        if (p.getDataValidade() != null) {
            txtDataValidade.setText(p.getDataValidade().format(formato));
        }
        
        // Seleciona o status correto na caixa de opções
        cmbStatus.setSelectedItem(p.getStatus());
    }
